"""V2 agent evaluation: build the evaluation dataset and score the agent on it.

    uv run agent-evaluate --build-dataset        # (re)load sample_data/eval/*.json into the UC dataset
    uv run agent-evaluate                        # evaluate the in-process agent (same code as the app)
    uv run agent-evaluate --category structured --limit 3

The dataset is an MLflow evaluation dataset in Unity Catalog. Its rows come from two files:
`eval_questions.json` (hand-written: document, structured, timeline, multi-source, out-of-scope) and
`eval_synthetic.json` (generated by scripts/generate_synthetic_evals.py, then reviewed).
"""
import argparse
import asyncio
import json
import logging
import os
import subprocess
import threading
from pathlib import Path

import mlflow
from dotenv import load_dotenv
from mlflow.genai.scorers import Correctness, RelevanceToQuery, RetrievalGroundedness, Safety
from mlflow.types.responses import ResponsesAgentRequest

load_dotenv(dotenv_path=".env", override=True)
logging.getLogger("mlflow.utils.autologging_utils").setLevel(logging.ERROR)

from agent_server import agent  # noqa: E402  (after .env: the agent reads its config at import)
from agent_server.eval_scorers import (  # noqa: E402
    cites_sources,
    latency_s,
    numbers_match,
    retrieved_expected_doc,
    tool_routing,
)

DATASET = "fins_genai.claims_multimodal_kb.agent_eval_v2"
EVAL_DIR = Path(__file__).resolve().parents[2] / "sample_data/eval"
SCORERS = [Correctness(), RelevanceToQuery(), RetrievalGroundedness(), Safety(),
           numbers_match, tool_routing, cites_sources, retrieved_expected_doc, latency_s]

# The agent's async clients are bound to the loop they first ran on, so every call runs on one
# long-lived loop (evaluate() calls predict_fn from worker threads).
_loop = asyncio.new_event_loop()
threading.Thread(target=_loop.run_forever, daemon=True).start()


def to_record(row: dict) -> dict:
    """A hand-written eval_questions.json row → dataset record."""
    expectations = {"expected_facts": row["expected_facts"]}
    for key in ("expected_numbers", "expected_tools"):
        if key in row:
            expectations[key] = row[key]
    return {"inputs": {"question": row["question"], "claim_id": row["claim_id"], "category": row["category"],
                       "id": row["id"]},
            "expectations": expectations}


def load_records() -> list[dict]:
    records = [to_record(r) for r in json.loads((EVAL_DIR / "eval_questions.json").read_text())]
    for r in json.loads((EVAL_DIR / "eval_synthetic.json").read_text()):
        records.append({"inputs": {**r["inputs"], "category": "document", "id": r["id"]},
                        "expectations": r["expectations"]})
    return records


def build_dataset() -> None:
    """Create the UC dataset (linked to the app's experiment) on first use, then upsert every row."""
    try:
        dataset = mlflow.genai.datasets.get_dataset(name=DATASET)
    except Exception:  # not created yet
        dataset = mlflow.genai.datasets.create_dataset(name=DATASET, experiment_id=os.environ["MLFLOW_EXPERIMENT_ID"])
    records = load_records()
    dataset.merge_records(records)
    print(f"{len(records)} records merged into {DATASET}")


def predict_fn(question: str, claim_id: str | None = None, **_) -> str:
    """Ask the agent the way the UI does (the selected claim is prefixed) and return its answer text."""
    content = f"[Claim {claim_id}] {question}" if claim_id else question
    request = ResponsesAgentRequest(input=[{"role": "user", "content": content}])
    response = asyncio.run_coroutine_threadsafe(agent.invoke_handler(request), _loop).result()
    texts = []
    for item in response.output:
        item = item if isinstance(item, dict) else item.model_dump()
        if item.get("type") == "message":
            texts += [part.get("text", "") for part in item.get("content", [])]
    return texts[-1] if texts else ""


def evaluate() -> None:
    parser = argparse.ArgumentParser(prog="agent-evaluate")
    parser.add_argument("--build-dataset", action="store_true", help="load sample_data/eval/*.json into UC")
    parser.add_argument("--category", help="only rows of this category (document, structured, timeline, ...)")
    parser.add_argument("--limit", type=int, help="only the first N rows (quick smoke run)")
    args = parser.parse_args()
    if args.build_dataset:
        build_dataset()
        return

    data = mlflow.genai.datasets.get_dataset(name=DATASET).to_df()
    if args.category:
        data = data[data["inputs"].map(lambda i: i.get("category") == args.category)]
    if args.limit:
        data = data.head(args.limit)
    sha = subprocess.run(["git", "rev-parse", "--short", "HEAD"], capture_output=True, text=True).stdout.strip()
    with mlflow.start_run(run_name=f"v2-eval-{sha}" + (f"-{args.category}" if args.category else "")):
        results = mlflow.genai.evaluate(data=data, predict_fn=predict_fn, scorers=SCORERS)
    print(json.dumps(results.metrics, indent=2, default=str))
